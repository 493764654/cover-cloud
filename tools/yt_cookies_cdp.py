#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""从本机 Chrome 通过 CDP 导出 cookies.txt（绕过 Chrome v127+ 的 App-Bound 加密）

用法：python tools/yt_cookies_cdp.py [输出路径] [--keep]
会做：关闭 Chrome → 带调试端口重启 → Storage.getCookies → 写 Netscape cookies.txt → 关调试 Chrome → 恢复普通 Chrome
"""
import json
import os
import subprocess
import sys
import time
import urllib.request

CHROME = r"C:\Program Files\Google\Chrome\Application\chrome.exe"
USER_DATA = r"C:\Users\Administrator\AppData\Local\Google\Chrome\User Data"
PORT = 9333
OUT = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("--") else \
    r"D:\DSHgongzuoqualiyun\cover\win\yt_cookies.txt"


def chrome_running() -> bool:
    p = subprocess.run(["tasklist"], capture_output=True, text=True, errors="replace")
    return "chrome.exe" in (p.stdout or "").lower()


def kill_chrome():
    subprocess.run(["taskkill", "/IM", "chrome.exe", "/F"], capture_output=True)
    for _ in range(20):
        if not chrome_running():
            return True
        time.sleep(0.5)
    return False


def start_debug_chrome():
    subprocess.Popen([CHROME, f"--user-data-dir={USER_DATA}", "--profile-directory=Default",
                      f"--remote-debugging-port={PORT}", "--no-first-run",
                      "--no-default-browser-check", "--restore-last-session=false",
                      "https://www.youtube.com/"],
                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def ws_url() -> str:
    """取 youtube 那个 page target 的 ws（browser 级拿不到 cookie，必须 page 级）。"""
    for _ in range(60):
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{PORT}/json", timeout=2) as r:
                targets = json.load(r)
            for t in targets:
                if t.get("type") == "page" and "youtube" in (t.get("url") or ""):
                    return t["webSocketDebuggerUrl"]
            for t in targets:
                if t.get("type") == "page":
                    return t["webSocketDebuggerUrl"]
        except Exception:  # noqa: BLE001
            pass
        time.sleep(0.5)
    raise SystemExit("调试端口没起来")


def cdp_get_cookies(url: str) -> list:
    from websockets.sync.client import connect

    with connect(url, max_size=64 * 1024 * 1024, open_timeout=15) as ws:
        ws.send(json.dumps({"id": 1, "method": "Storage.getCookies", "params": {}}))
        for _ in range(50):
            msg = json.loads(ws.recv(timeout=30))
            if msg.get("id") == 1:
                if "error" in msg:
                    raise SystemExit(f"CDP 错误: {msg['error']}")
                return msg["result"]["cookies"]
    raise SystemExit("CDP 无响应")


def to_netscape(cookies: list) -> str:
    lines = ["# Netscape HTTP Cookie File", "# generated by yt_cookies_cdp.py", ""]
    n = 0
    for c in cookies:
        dom = c.get("domain") or ""
        if not dom:
            continue
        if "youtube" not in dom and "google" not in dom:
            continue
        exp = int(c.get("expires") or 0)
        if exp <= 0:
            exp = int(time.time()) + 365 * 86400
        lines.append("\t".join([
            dom, "TRUE" if dom.startswith(".") else "FALSE",
            c.get("path") or "/", "TRUE" if c.get("secure") else "FALSE",
            str(exp), c.get("name", ""), c.get("value", ""),
        ]))
        n += 1
    print(f"[cookies] 导出 {n} 条 youtube/google cookie")
    return "\n".join(lines) + "\n"


def main():
    was_running = chrome_running()
    print("[1/5] 关闭 Chrome…", "（原本在运行）" if was_running else "（本就没开）")
    kill_chrome()
    print("[2/5] 带调试端口启动 Chrome…")
    start_debug_chrome()
    url = ws_url()
    print("[3/5] 连 CDP 取 cookies…", url)
    cookies = cdp_get_cookies(url)
    text = to_netscape(cookies)
    os.makedirs(os.path.dirname(OUT) or ".", exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"[4/5] 写入 {OUT} ({os.path.getsize(OUT)} bytes)")
    if "--keep" not in sys.argv:
        print("[5/5] 关闭调试 Chrome，恢复普通 Chrome…")
        subprocess.run(["taskkill", "/IM", "chrome.exe", "/F"], capture_output=True)
        time.sleep(2)
        subprocess.Popen([CHROME], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    print("DONE")


if __name__ == "__main__":
    main()
